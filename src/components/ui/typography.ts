// Типографика текстов, которые приходят из данных (название комнаты): короткие
// слова не остаются висеть в конце строки. Чистая функция — её же берут
// OG-картинки (src/lib/ogCard.tsx), там satori тоже не рвёт строку на U+00A0.

// Короткие слова (предлоги, союзы, частицы: «в», «с», «и», «не», «для»…),
// после которых нельзя рвать строку: «с» в конце строки висит отдельно от слова.
const SHORT_WORD = /(?<=^|[\s(«„"])([а-яё]{1,2}|для|без|над|под|при|про|обо|изо|через)\s+(?=\S)/giu;

/** Неразрывный пробел после коротких слов: «катка в CS2 с Тёмой» не кончит строку на «в» или «с». */
export function glueShortWords(text: string): string {
  return text.replace(SHORT_WORD, "$1 ");
}
